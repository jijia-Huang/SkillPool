def section_text(text: str, heading: str) -> str | None:
    """The `#`/`##` section titled `heading`, through the next heading of the same or higher level."""
    lines, start, level, in_code = text.splitlines(), None, 0, False
    for i, line in enumerate(lines):
        if line.lstrip().startswith("```"):
            in_code = not in_code
        m = None if in_code else re.match(r"^(#{1,6})\s+(.*?)\s*$", line)
        if not m:
            continue
        if start is None and m.group(2) == heading.strip():
            start, level = i, len(m.group(1))
        elif start is not None and len(m.group(1)) <= level:
            return "\n".join(lines[start:i]).strip()
    return "\n".join(lines[start:]).strip() if start is not None else None


def expand(path: str, base: Path) -> Path:
    p = Path(os.path.expandvars(os.path.expanduser(path)))
    return p if p.is_absolute() else (base / p)


def append_text(profile: dict, warnings: list[str]) -> str:
    parts = []
    base = profile["path"].parent
    for item in profile["data"].get("instructions", {}).get("append", []):
        file, section = (item, None) if isinstance(item, str) else (item["file"], item.get("section"))
        f = expand(file, base)
        if not f.is_file():
            warnings.append(f"instructions.append: {fwd(f)} not found, skipped")
            continue
        text = f.read_text(encoding="utf-8", errors="replace")
        if section:
            body = section_text(text, section)
            if body is None:
                warnings.append(f"instructions.append: section '{section}' not in {fwd(f)}, skipped")
                continue
            text = body
        parts.append(text.strip())
    return "\n\n".join(parts)


def exclude_globs(kinds: list[str], cwd: Path) -> list[str]:
    """claudeMdExcludes patterns. CLAUDE.md shadows AGENTS.md in the same folder, so both go."""
    globs: list[str] = []
    for k in kinds:
        if k == "user":
            globs += [fwd(CLAUDE / n) for n in INSTRUCTION_FILES] + [fwd(CLAUDE / "rules") + "/**"]
        elif k == "project":
            for d in [cwd, *cwd.parents]:
                if scan.norm_path(d) == scan.norm_path(HOME):
                    continue  # home's .claude/CLAUDE.md is the user file
                globs += [fwd(d / n) for n in INSTRUCTION_FILES]
                globs += [fwd(d / ".claude" / "CLAUDE.md"), fwd(d / ".claude" / "rules") + "/**"]
            globs += [fwd(cwd) + "/**/" + n for n in INSTRUCTION_FILES]
        else:
            globs.append(k)
    return list(dict.fromkeys(globs))


def resolve(profile: dict, cwd: Path) -> dict:
    """Turn a profile into settings / MCP config / appended prompt / extra CLI args."""
    data = profile["data"]
    warnings: list[str] = []  # something in the profile did not resolve
    notes: list[str] = []  # expected limits of the native mechanisms
    settings: dict = {}
    plugins = installed_plugins()

    # skills
    sk = data.get("skills", {})
    overrides: dict[str, str] = {}
    overridable, plugin_skills = skill_universe(cwd)
    if "only" in sk:
        keep = set(sk["only"])
        others = sk.get("others", "user-invocable-only")
        already = current_overrides(cwd)
        for n in sorted(overridable - keep):
            if already.get(n) != "off":  # never loosen a skill the user switched off
                overrides[n] = others
        for n in keep:
            overrides[n] = "on"
        still = sorted(s for s in plugin_skills if s not in keep
                       and plugin_id(s.split(":")[0], plugins) not in
                       {plugin_id(p, plugins) for p in data.get("plugins", {}).get("off", [])})
        if still:
            notes.append(f"skills.only cannot hide plugin skills ({len(still)}): " + ", ".join(still)
                            + ". Add their plugin to plugins.off to drop it")
    for key, mode in (("on", "on"), ("off", "off"), ("nameOnly", "name-only"), ("userOnly", "user-invocable-only")):
        for n in sk.get(key, []):
            if n in plugin_skills:
                warnings.append(f"skills.{key}: '{n}' is a plugin skill; skillOverrides cannot change it")
                continue
            overrides[n] = mode
    for n in set(sk.get("only", [])) | {x for k in ("on", "off", "nameOnly", "userOnly") for x in sk.get(k, [])}:
        if n not in overridable and n not in plugin_skills:
            warnings.append(f"skill '{n}' not found here (run `skillpool check` to refresh built-in names)")
    if overrides:
        settings["skillOverrides"] = overrides

    # plugins
    enabled: dict[str, bool] = {}
    for key, val in (("off", False), ("on", True)):
        for n in data.get("plugins", {}).get(key, []):
            pid = plugin_id(n, plugins)
            if not pid:
                warnings.append(f"plugins.{key}: no installed plugin '{n}'")
                continue
            enabled[pid] = val
    if enabled:
        settings["enabledPlugins"] = enabled
    off_plugins = {pid for pid, v in enabled.items() if not v}

    # MCP
    mcp = data.get("mcp", {})
    deny: list[str] = []
    mcp_config = None
    prefixes = known_mcp_prefixes(cwd)
    if "off" in mcp:
        for n in mcp["off"]:
            deny.append(mcp_prefix(n))
            if mcp_prefix(n) not in prefixes:
                warnings.append(f"mcp.off: server '{n}' not seen here")
        notes.append("mcp.off hides tools only: a hidden server still connects and its server "
                        "instructions stay in the prompt. Use mcp.only for full removal")
    elif "only" in mcp:
        want = set(mcp["only"])
        servers: dict[str, dict] = {}
        for n, origin, cfg in raw_mcp_sources(cwd):
            if n not in want or n in servers:
                continue
            if origin.startswith("plugin:"):
                pid = origin.split(":", 1)[1]
                if pid in off_plugins:
                    continue
                root = fwd(plugins[pid]["root"])
                cfg = json.loads(json.dumps(cfg).replace("${CLAUDE_PLUGIN_ROOT}", root))
            servers[n] = cfg
        for n in sorted(want - set(servers)):
            if n.startswith("claude.ai"):
                warnings.append(f"mcp.only: claude.ai connector '{n}' cannot be kept under mcp.only")
            elif mcp_prefix(n) not in prefixes:
                warnings.append(f"mcp.only: server '{n}' not configured here")
        mcp_config = {"mcpServers": servers}
        # tools a mod registers itself are not MCP config, so strict mode leaves them: hide by name
        configured = {mcp_prefix(n) for n, _, _ in raw_mcp_sources(cwd)}
        for p, n in prefixes.items():
            if p not in configured and n not in want and not n.startswith("claude.ai") \
                    and not p.startswith("mcp__claude_ai_"):
                deny.append(p)
    if deny:
        settings["permissions"] = {"deny": sorted(set(deny))}

    # instructions
    ins = data.get("instructions", {})
    if ins.get("exclude"):
        settings["claudeMdExcludes"] = exclude_globs(ins["exclude"], cwd)
    prompt = append_text(profile, warnings)

    args: list[str] = []
    if data.get("model"):
        args += ["--model", data["model"]]
    if data.get("effort"):
        args += ["--effort", data["effort"]]
    return {"settings": settings, "mcp_config": mcp_config, "append": prompt, "args": args,
            "warnings": warnings, "notes": notes}


# ---------------------------------------------------------------- launch


def claude_exe() -> str:
    exe = shutil.which("claude")
    if not exe:
        raise UserError("`claude` is not on PATH")
    return exe


def write_run_files(name: str, plan: dict) -> tuple[list[str], list[Path]]:
    RUN_DIR.mkdir(parents=True, exist_ok=True)
    stem = f"{name}-{os.getpid()}"
    args, files = [], []
    if plan["settings"]:
        f = RUN_DIR / f"{stem}-settings.json"
        f.write_text(json.dumps(plan["settings"], ensure_ascii=False, indent=2), encoding="utf-8")
        args += ["--settings", str(f)]
        files.append(f)
    if plan["mcp_config"] is not None:
        f = RUN_DIR / f"{stem}-mcp.json"
        f.write_text(json.dumps(plan["mcp_config"], ensure_ascii=False, indent=2), encoding="utf-8")
        args += ["--strict-mcp-config", "--mcp-config", str(f)]
        files.append(f)
    if plan["append"]:
        f = RUN_DIR / f"{stem}-prompt.md"
        f.write_text(f"# SkillPool profile: {name}\n\n{plan['append']}\n", encoding="utf-8")
        args += ["--append-system-prompt-file", str(f)]
        files.append(f)
    return args, files


def has_flag(args: list[str], *flags: str) -> bool:
    return any(a in flags or any(a.startswith(f + "=") for f in flags) for a in args)


def launch(name: str | None, passthrough: list[str], cwd: Path) -> int:
    exe = claude_exe()
    if not name:
        err("skillpool: no profile (pass one or set AGENT_PROFILE); starting plain claude")
        return subprocess.call([exe, *passthrough])
    profile = get_profile(cwd, name)
    plan = resolve(profile, cwd)
    for w in plan["warnings"]:
        err(f"skillpool: warning: {w}")
    run_args, files = write_run_files(name, plan)
    args = [exe, *run_args]
    # the user's own flags win over the profile's
    for flag, val in zip(plan["args"][::2], plan["args"][1::2]):
        if not has_flag(passthrough, flag):
            args += [flag, val]
    if not has_flag(passthrough, "-n", "--name", "-r", "--resume", "-c", "--continue", "-p", "--print"):
        args += ["--name", name]
    args += passthrough
    env = dict(os.environ, AGENT_PROFILE=name)
    err(f"skillpool: profile '{name}' ({profile['scope']})")
    try:
        return subprocess.call(args, env=env)
    except KeyboardInterrupt:
        return 130
    finally:
        for f in files:  # the MCP run file can hold secrets: never leave it behind
            try:
                f.unlink()
            except OSError:
                pass


