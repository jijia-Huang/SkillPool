def yaml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def agent_text(profile: dict, cwd: Path) -> str:
    data = profile["data"]
    ag = data.get("agent") or {}
    plan = resolve(profile, cwd)
    desc = data.get("description", "").strip() or profile["name"]
    when = data.get("whenToUse", "").strip()
    sep = "" if desc[-1] in ".。!！?？" else "."
    when = re.sub(r"^use (it |this )?when[:,]?\s*", "", when, flags=re.I)
    description = f"[SkillPool profile: {profile['name']}] {desc}{sep}" + (f" Use when: {when}" if when else "")
    # only server-level MCP denies are safe here: a Skill(x) entry would remove the whole Skill tool
    deny = [d for d in plan["settings"].get("permissions", {}).get("deny", []) if d.startswith("mcp__")]
    if plan["mcp_config"] is not None:
        keep = {mcp_prefix(n) for n in plan["mcp_config"]["mcpServers"]}
        deny += [p for p in known_mcp_prefixes(cwd) if p not in keep]
    plugins = installed_plugins()
    for pid, on in plan["settings"].get("enabledPlugins", {}).items():
        if not on:
            deny += [mcp_prefix(n) for n in plugin_mcp_servers(plugins[pid]["root"])]
            deny.append(mcp_prefix(plugins[pid]["name"]))  # tools a plugin's mod registers
    deny += ag.get("disallowedTools", [])
    deny = sorted(set(deny))
    fm = ["---", f"name: {AGENT_PREFIX}{profile['name']}", f"description: {yaml_str(description)}"]
    if ag.get("tools"):
        fm.append("tools: " + ", ".join(ag["tools"]))
    if deny:
        fm.append("disallowedTools: " + ", ".join(deny))
    if ag.get("preloadSkills"):
        fm.append("skills: " + ", ".join(ag["preloadSkills"]))
    model = ag.get("model") or data.get("model")
    if model:
        fm.append(f"model: {model}")
    if ag.get("omitClaudeMd"):
        fm.append("omitClaudeMd: true")
    fm.append("---")
    body = [AGENT_MARKER, "",
            f"You are a subagent running under the SkillPool profile `{profile['name']}`.",
            f"Scope: {desc}" + (f" ({when})" if when else ""),
            f"Before you start, read `{fwd(profile['dir'] / 'CLAUDE.md')}` and follow it: it holds this profile's "
            "rules, its cross-project memory and an index of its per-project memory.",
            f"This project's memory is `{fwd(profile['dir'])}/memory/<project-key>/MEMORY.md` (project-key: the "
            "project root's path with every character other than A-Z, a-z, 0-9 replaced by `-`); read it if it "
            "exists. Save new memory there (one file per fact plus a line in MEMORY.md), never in "
            "`~/.claude/projects/*/memory/`.",
            "Stay within that scope. If the task needs tools or skills outside it, say so in your reply "
            "instead of working around it."]
    skills = data.get("skills", {}).get("use", []) + own_skills(profile)
    if skills:
        body.append("This profile's skills (if the Skill tool does not list one, read its SKILL.md directly): "
                    + "; ".join(f"{n} = `{fwd(profile_skill_dir(profile) / n / 'SKILL.md')}`" for n in skills))
    if plan["append"]:
        body += ["", plan["append"]]
    return "\n".join(fm) + "\n" + "\n".join(body) + "\n"


def write_agents(only: str | None = None, dry_run: bool = False) -> int:
    cwd = Path.cwd()
    profiles = load_profiles()
    wanted: dict[Path, str] = {}
    for p in profiles.values():
        if p["errors"] or p["data"].get("agent") is False or (only and p["name"] != only):
            continue
        wanted[CLAUDE / "agents" / f"{AGENT_PREFIX}{p['name']}.md"] = agent_text(p, cwd)
    for path, text in wanted.items():
        old = path.read_text(encoding="utf-8") if path.is_file() else None
        if old is not None and AGENT_MARKER not in old:
            err(f"skillpool: {fwd(path)} exists and was not generated by skillpool; left alone")
            continue
        if old == text:
            out(f"agent unchanged: {fwd(path)}")
            continue
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        out(f"agent {'would write' if dry_run else 'written'}: {fwd(path)}")
    if only is None:  # drop generated agents whose profile is gone
        d = CLAUDE / "agents"
        for f in d.glob(f"{AGENT_PREFIX}*.md") if d.is_dir() else []:
            if f not in wanted and AGENT_MARKER in f.read_text(encoding="utf-8", errors="replace") \
                    and f.stem[len(AGENT_PREFIX):] not in profiles:
                if not dry_run:
                    f.unlink()
                out(f"stale agent {'would remove' if dry_run else 'removed'}: {fwd(f)}")
    return 0


