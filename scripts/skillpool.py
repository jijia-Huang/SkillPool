"""SkillPool: launch Claude Code with a profile, and manage profiles.

A profile narrows what one session sees (skills, plugins, MCP servers,
instruction files) using Claude Code's own settings, so sessions in the same
folder can run with different setups:

    skillpool <profile> [claude args...]   start claude with that profile
    skillpool [claude args...]             profile from $AGENT_PROFILE, else plain claude
    skillpool list [--json]                profiles visible from this folder
    skillpool show <profile> [--json]      what a profile changes, without launching
    skillpool check [<profile>]            start claude headless and read what really loaded
    skillpool save <draft.json> [--name N] [--scope user|project] [--force]
    skillpool rm <profile> [--force]
    skillpool agents [--dry-run]           regenerate the skillpool-<profile> subagents
    skillpool install-shim [--dir D]       put a `skillpool` command on PATH

Console output is ASCII only (Chinese text goes to UTF-8 files or \\u escapes).
"""

