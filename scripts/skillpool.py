def cmd_session(rest: list[str]) -> int:
    action = rest.pop(0) if rest else ""
    if action == "sweep":
        for n in sweep_sessions():
            out(f"removed stale link: {n}")
        return 0
    link_arg = take_value(rest, "--link")
    if not link_arg:
        raise UserError("usage: skillpool session attach --link L --cwd C (<profile> | --empty) | detach --link L")
    link = Path(link_arg)
    if scan.norm_path(link.parent) != scan.norm_path(SESSIONS):
        raise UserError(f"session links live in {fwd(SESSIONS)}")
    if action == "detach":
        if is_link(link):
            remove_link(link)
        (SESSIONS / f"{link.name}.alive").unlink(missing_ok=True)
        out(f"detached: {link.name}")
        return 0
    if action != "attach":
        raise UserError(f"unknown session action '{action}'")
    cwd = Path(take_value(rest, "--cwd") or os.getcwd())
    with_context = take_flag(rest, "--context")
    if take_flag(rest, "--empty"):
        EMPTY.mkdir(parents=True, exist_ok=True)
        make_link(link, EMPTY)
        out("attached: (none)")
        return 0
    if len(rest) != 1:
        raise UserError("session attach needs one profile name")
    profile = get_profile(rest[0])
    sweep_sessions()
    for m in prepare(profile, cwd, link):
        out(m)
    if link.name.startswith("m-"):
        (SESSIONS / f"{link.name}.alive").write_text(datetime.now().isoformat(), encoding="utf-8")
    plan = resolve(profile, cwd)
    out(f"attached: {profile['name']}")
    out(f"memory: {fwd(plan['memory'])}")
