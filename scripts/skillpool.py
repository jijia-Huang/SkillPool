def backup(path: Path) -> Path:
    d = BACKUP_DIR / "profiles" / datetime.now().strftime("%Y%m%d-%H%M%S")
    d.mkdir(parents=True, exist_ok=True)
    dest = d / (path.parent.name + "-" + path.name)
    shutil.copy2(path, dest)
    return dest


def write_or_diff(path: Path, old: str, new: str, label: str, force: bool, compare=lambda t: t) -> int | None:
    """Same text: 0. Different and not forced: a diff for the user, 3. Forced: back up and go on (None)."""
    if compare(old) == compare(new):
        out(f"unchanged: {fwd(path)}")
        return 0
    dfile = RUN_DIR / f"diff-{label}.diff"
    if not force:
        diff = "".join(difflib.unified_diff(compare(old).splitlines(True), compare(new).splitlines(True),
                                            fromfile=f"{label} (current)", tofile=f"{label} (new)"))
        RUN_DIR.mkdir(parents=True, exist_ok=True)
        dfile.write_text(diff, encoding="utf-8")
        out(f"EXISTS: {fwd(path)} would change.")
        out(f"diff written to {fwd(dfile)} (UTF-8). Show it to the user; after they approve, rerun with --force.")
        return 3
    out(f"backup: {fwd(backup(path))}")
    dfile.unlink(missing_ok=True)
    return None


def cmd_save(draft: Path, name: str | None, force: bool) -> int:
    """profile.json or CLAUDE.md. New: written directly. Existing: a diff for the user, unless --force."""
    if draft.suffix.lower() == ".md":
        if not name:
            raise UserError("saving a CLAUDE.md draft needs --name <profile>")
        profile = get_profile(name)
        md = profile["dir"] / "CLAUDE.md"
        new = draft.read_text(encoding="utf-8")
        if md.is_file():
            # the memory index is SkillPool's own: the diff and the write leave it to update_index()
            done = write_or_diff(md, md.read_text(encoding="utf-8"), new, f"{name}-CLAUDE.md", force, strip_index)
            if done is not None:
                return done
        md.write_text(new, encoding="utf-8")
        update_index(profile)
        out(f"saved: {fwd(md)}")
        write_agents(only=name)
        return 0
    prof = draft_profile(draft, name)
    name, data, path = prof["name"], prof["data"], prof["path"]
    new_text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    if path.is_file():
        done = write_or_diff(path, path.read_text(encoding="utf-8"), new_text, f"{name}-profile.json", force)
        if done is not None:
            return done
    else:
        (prof["dir"] / "memory").mkdir(parents=True, exist_ok=True)
    path.write_text(new_text, encoding="utf-8")
    md = prof["dir"] / "CLAUDE.md"
    if not md.is_file():
        md.write_text(claude_md_template(name, data.get("description", "")), encoding="utf-8")
    update_index(prof)
    for m in sync_skills(prof):
        out(m)
    out(f"saved: {fwd(path)}")
    if data.get("agent") is not False:
        write_agents(only=name)
    return 0


def cmd_rm(name: str, force: bool) -> int:
    profiles = load_profiles()
    if name not in profiles:
        raise UserError(f"no profile '{name}'")
    d = profiles[name]["dir"]
    users = [link.name for link in (SESSIONS.iterdir() if SESSIONS.is_dir() else [])
             if is_link(link) and same_path(link_target(link), d)]
    if not force:
        out(f"would move {fwd(d)} (rules, memory, skill links) to {fwd(BACKUP_DIR / 'profiles')} and remove its "
            f"generated agent. Ask the user, then rerun with --force.")
        if users:
            out("sessions using it now: " + ", ".join(users))
        return 3
    dest = BACKUP_DIR / "profiles" / datetime.now().strftime("%Y%m%d-%H%M%S")
    dest.mkdir(parents=True, exist_ok=True)
    os.rename(d, dest / name)  # a rename never walks into the links inside
    agent = CLAUDE / "agents" / f"{AGENT_PREFIX}{name}.md"
    if agent.is_file() and AGENT_MARKER in agent.read_text(encoding="utf-8", errors="replace"):
        agent.unlink()
        out(f"removed agent: {fwd(agent)}")
    out(f"moved to backup: {fwd(dest / name)}")
    if users:
        out("these sessions now point at a missing profile; switch them with /skillpool: " + ", ".join(users))
    return 0


