def read_cache() -> dict:
    return scan.read_json(CACHE_FILE) or {}


def installed_plugins() -> dict[str, dict]:
    """plugin id (name@marketplace) -> {name, root, enabled_user}."""
    user_enabled = (scan.read_json(CLAUDE / "settings.json") or {}).get("enabledPlugins", {}) or {}
    installed = (scan.read_json(CLAUDE / "plugins" / "installed_plugins.json") or {}).get("plugins", {})
    res = {}
    for key, entries in installed.items():
        ents = entries if isinstance(entries, list) else [entries]
        root = next((Path(e["installPath"]) for e in ents if e.get("installPath")), None)
        res[key] = {"name": key.split("@")[0], "root": root, "enabled_user": user_enabled.get(key)}
    return res


def plugin_id(name: str, plugins: dict[str, dict]) -> str | None:
    if name in plugins:
        return name
    hits = [k for k, v in plugins.items() if v["name"] == name]
    return hits[0] if len(hits) == 1 else None


def plugin_mcp_servers(root: Path | None) -> dict[str, dict]:
    if not root:
        return {}
    pm = scan.read_json(root / ".mcp.json") or {}
    servers = pm.get("mcpServers") if isinstance(pm.get("mcpServers"), dict) else pm
    return {n: c for n, c in servers.items() if isinstance(c, dict)}


def project_mcp_approval(cwd: Path) -> tuple[set[str] | None, set[str]]:
    """(approved project .mcp.json server names, None when all are; disabled names), as the user decided."""
    root = project_root(cwd)
    enabled: set[str] = set()
    disabled: set[str] = set()
    every = False
    sources = [scan.read_json(f) or {} for f in (CLAUDE / "settings.json", CLAUDE / "settings.local.json",
                                                root / ".claude" / "settings.json",
                                                root / ".claude" / "settings.local.json")]
    cj = scan.read_json(HOME / ".claude.json") or {}
    sources += [v for p, v in (cj.get("projects") or {}).items()
                if isinstance(v, dict) and scan.norm_path(p) == scan.norm_path(root)]
    for d in sources:
        enabled |= set(d.get("enabledMcpjsonServers") or [])
        disabled |= set(d.get("disabledMcpjsonServers") or [])
        every = every or d.get("enableAllProjectMcpServers") is True
    return (None if every else enabled), disabled


def raw_mcp_sources(cwd: Path, project: str = "approved") -> list[tuple[str, str, dict]]:
    """(name, origin, raw config) for servers Claude Code would load here, plugins included.
    project: "approved" (the project's .mcp.json servers the user approved), "all" or "none".
    Raw configs can hold secrets: they are only ever written to the per-launch run file."""
    res: list[tuple[str, str, dict]] = []
    cj = scan.read_json(HOME / ".claude.json") or {}
    for n, c in (cj.get("mcpServers") or {}).items():
        res.append((n, "user", c))
    here = {scan.norm_path(d) for d in [cwd, *cwd.parents]}
    for p, v in (cj.get("projects") or {}).items():
        if scan.norm_path(p) in here:
            for n, c in (v.get("mcpServers") or {}).items():
                res.append((n, f"local:{p}", c))
    if project != "none":
        approved, disabled = project_mcp_approval(cwd)
        for n, c in ((scan.read_json(project_root(cwd) / ".mcp.json") or {}).get("mcpServers") or {}).items():
            if project == "all" or ((approved is None or n in approved) and n not in disabled):
                res.append((n, "project", c))
    for key, info in installed_plugins().items():
        if info["enabled_user"] is False:
            continue
        for n, c in plugin_mcp_servers(info["root"]).items():
            res.append((n, f"plugin:{key}", c))
    return res


def skill_universe(cwd: Path) -> tuple[set[str], set[str]]:
    """(names skillOverrides can switch, plugin skill names it cannot)."""
    root = scan.norm_path(project_root(cwd))
    inv = scan.inventory([str(project_root(cwd))])
    overridable = {s["name"] for s in inv["skills"] if s["source"] != "plugin"}
    plugin_skills = {s["name"] for s in inv["skills"] if s["source"] == "plugin"
                     and (s.get("scope") == "user" or root in {scan.norm_path(p) for p in s.get("projects") or []})}
    overridable |= scan.BUNDLED_SKILLS
    plugin_names = {v["name"] for v in installed_plugins().values()}
    for n in read_cache().get("skills", []):
        if ":" in n and n.split(":")[0] in plugin_names:
            plugin_skills.add(n)
        else:
            overridable.add(n)  # bundled and claude.ai skills (anthropic-skills:*) seen by `check`
    return overridable, plugin_skills


def known_mcp_prefixes(cwd: Path) -> dict[str, str]:
    """tool prefix -> server name, from configs plus what `check` saw (claude.ai connectors, mod tools)."""
    res = {mcp_prefix(n): n for n, _, _ in raw_mcp_sources(cwd, "all")}
    for n in read_cache().get("mcp", []):
        res.setdefault(mcp_prefix(n), n)
    for p in read_cache().get("mcp_prefixes", []):
        res.setdefault(p, p[len("mcp__"):])
    return res


