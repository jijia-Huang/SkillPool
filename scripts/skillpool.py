def probe(extra: list[str], env: dict | None = None, cwd: Path | None = None) -> dict:
    """Start claude headless, read its init event (skills, MCP, agents, plugins) and stop it."""
    cmd = [claude_exe(), "-p", "reply OK", "--output-format", "stream-json", "--verbose", "--model", "haiku",
           "--max-turns", "1", *extra]
    p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, stdin=subprocess.DEVNULL,
                         text=True, encoding="utf-8", errors="replace", env=env, cwd=cwd)
    init = None
    deadline = time.time() + 120
    try:
        for line in p.stdout:
            if '"subtype":"init"' in line.replace(" ", ""):
                init = json.loads(line)
                break
            if time.time() > deadline:
                break
    finally:
        p.kill()
        p.wait()
    if not init:
        raise UserError("claude did not report its init event (is it logged in?)")
    tools = init.get("tools", [])
    return {
        "skills": init.get("skills", []),
        "mcp": [s.get("name") for s in init.get("mcp_servers", [])],
        "mcp_status": {s.get("name"): s.get("status") for s in init.get("mcp_servers", [])},
        "mcp_prefixes": sorted({"mcp__" + t.split("__")[1] for t in tools if t.startswith("mcp__")}),
        "agents": init.get("agents", []),
        "plugins": [x.get("name") if isinstance(x, dict) else x for x in init.get("plugins", [])],
    }


def cmd_check(name: str | None, cwd: Path, as_json: bool) -> int:
    base = probe([], cwd=cwd)
    cache = read_cache()
    for k in ("skills", "mcp", "mcp_prefixes"):
        cache[k] = sorted(set(cache.get(k, [])) | set(base[k]))
    cache["updated"] = datetime.now().astimezone().isoformat(timespec="seconds")
    CACHE_FILE.parent.mkdir(parents=True, exist_ok=True)
    CACHE_FILE.write_text(json.dumps(cache, ensure_ascii=False, indent=2), encoding="utf-8")
    result = {"base": base}
    if name:
        profile = get_profile(cwd, name)
        plan = resolve(profile, cwd)
        run_args, files = write_run_files(name, plan)
        try:
            got = probe(run_args + plan["args"], env=dict(os.environ, AGENT_PROFILE=name), cwd=cwd)
        finally:
            for f in files:
                f.unlink(missing_ok=True)
        hidden = {k: v for k, v in plan["settings"].get("skillOverrides", {}).items() if v != "on"}
        result |= {"profile": name, "loaded": got, "warnings": plan["warnings"], "notes": plan["notes"],
                   "removed": {k: sorted(set(base[k]) - set(got[k])) for k in ("skills", "mcp", "mcp_prefixes",
                                                                                 "agents", "plugins")},
                   "listing_hidden_but_slash_ok": sorted(n for n, v in hidden.items()
                                                         if v == "user-invocable-only" and n in got["skills"])}
    if as_json:
        out(json.dumps(result, ensure_ascii=True, indent=2))
        return 0
    view = result.get("loaded", base)
    title = f"profile '{name}'" if name else "no profile"
    out(f"{title}: as loaded by claude in {fwd(cwd)}")
    if name:
        hidden_ok = set(result["listing_hidden_but_slash_ok"])
        model_skills = [s for s in view["skills"] if s not in hidden_ok]
        out(f"  skills the model sees ({len(model_skills)}): " + ", ".join(model_skills))
        out(f"  slash-only, hidden from the model ({len(hidden_ok)})")
    else:
        out(f"  skills ({len(view['skills'])}): " + ", ".join(view["skills"]))
    out(f"  mcp servers: " + ", ".join(f"{n} [{view['mcp_status'].get(n)}]" for n in view["mcp"]))
    out(f"  mcp tool prefixes: " + ", ".join(view["mcp_prefixes"]))
    out(f"  agents ({len(view['agents'])}): " + ", ".join(view["agents"]))
    out(f"  plugins: " + ", ".join(view["plugins"]))
    if name:
        for k, v in result["removed"].items():
            if v:
                out(f"  removed {k}: " + ", ".join(v))
        for w in result["warnings"]:
            out(f"  warning: {w}")
        for w in result["notes"]:
            out(f"  note: {w}")
        out("  note: this init list includes slash-only skills; the model's listing excludes them")
    out(f"cache updated: {fwd(CACHE_FILE)}")
    return 0


