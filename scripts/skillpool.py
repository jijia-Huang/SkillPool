def cmd_list(cwd: Path, as_json: bool) -> int:
    profiles = load_profiles(cwd)
    rows = [{"name": p["name"], "scope": p["scope"], "path": fwd(p["path"]), "errors": p["errors"],
             "description": p["data"].get("description", ""), "whenToUse": p["data"].get("whenToUse", ""),
             "shadows": p.get("shadows")} for p in profiles.values()]
    if as_json:
        out(json.dumps(rows, ensure_ascii=True, indent=2))
        return 0
    if not rows:
        out(f"no profiles. Create one with `skillpool save <draft.json> --name <name>` "
            f"(user profiles: {fwd(USER_PROFILES)})")
        return 0
    for r in rows:
        flag = "  INVALID: " + "; ".join(r["errors"]) if r["errors"] else ""
        out(f"{r['name']:<20} {r['scope']:<8} {r['path']}{flag}")
    return 0


def cmd_show(name: str, cwd: Path, as_json: bool) -> int:
    profile = get_profile(cwd, name)
    plan = resolve(profile, cwd)
    cmd = ["claude"]
    if plan["settings"]:
        cmd += ["--settings", "<run>/settings.json"]
    if plan["mcp_config"] is not None:
        cmd += ["--strict-mcp-config", "--mcp-config", "<run>/mcp.json"]
    if plan["append"]:
        cmd += ["--append-system-prompt-file", "<run>/prompt.md"]
    cmd += plan["args"] + ["--name", name]
    view = {
        "profile": name, "scope": profile["scope"], "path": fwd(profile["path"]),
        "settings": plan["settings"],
        "mcp_servers": sorted((plan["mcp_config"] or {}).get("mcpServers", {})) if plan["mcp_config"] else None,
        "append_tokens": scan.est_tokens(plan["append"]),
        "command": " ".join(cmd), "warnings": plan["warnings"], "notes": plan["notes"],
    }
    if as_json:
        out(json.dumps(view, ensure_ascii=True, indent=2))
        return 0
    out(f"profile '{name}' ({profile['scope']}): {fwd(profile['path'])}")
    ov = plan["settings"].get("skillOverrides", {})
    by_mode: dict[str, list[str]] = {}
    for n, m in ov.items():
        by_mode.setdefault(m, []).append(n)
    for m in ("on", "name-only", "user-invocable-only", "off"):
        if m in by_mode:
            out(f"  skills {m} ({len(by_mode[m])}): " + ", ".join(sorted(by_mode[m])))
    for pid, v in plan["settings"].get("enabledPlugins", {}).items():
        out(f"  plugin {'on' if v else 'off'}: {pid}")
    if view["mcp_servers"] is not None:
        out("  mcp only (strict): " + (", ".join(view["mcp_servers"]) or "(none)"))
    if plan["settings"].get("permissions"):
        out("  tools hidden: " + ", ".join(plan["settings"]["permissions"]["deny"]))
    if plan["settings"].get("claudeMdExcludes"):
        out(f"  instruction files excluded: {len(plan['settings']['claudeMdExcludes'])} patterns")
    if plan["append"]:
        out(f"  appended instructions: ~{view['append_tokens']} tokens")
    out("  command: " + view["command"])
    for w in plan["warnings"]:
        out(f"  warning: {w}")
    for w in plan["notes"]:
        out(f"  note: {w}")
    return 0


# ---------------------------------------------------------------- save / rm


def target_path(name: str, scope: str, cwd: Path) -> Path:
    if scope == "user":
        return USER_PROFILES / f"{name}.json"
    root = project_root(cwd)
    if scan.norm_path(root) == scan.norm_path(HOME):
        raise UserError("no project here for --scope project")
    return root / ".claude" / "skillpool" / "profiles" / f"{name}.json"


def backup(path: Path) -> Path:
    d = BACKUP_DIR / "profiles" / datetime.now().strftime("%Y%m%d-%H%M%S")
    d.mkdir(parents=True, exist_ok=True)
    dest = d / path.name
    shutil.copy2(path, dest)
    return dest


def cmd_save(draft: Path, name: str | None, scope: str, force: bool, cwd: Path) -> int:
    """New profile: written directly. Existing profile: write a diff and stop unless --force."""
    try:
        data = json.loads(draft.read_text(encoding="utf-8"))
    except Exception as e:
        raise UserError(f"cannot read draft {fwd(draft)}: {e}")
    name = name or draft.stem
    if not NAME_RE.match(name) or name in SUBCOMMANDS:
        raise UserError(f"bad profile name '{name}': use lowercase letters, digits and '-', not a subcommand")
    errors = validate(data)
    if errors:
        raise UserError("draft is invalid: " + "; ".join(errors))
    path = target_path(name, scope, cwd)
    new_text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    if path.exists():
        old_text = path.read_text(encoding="utf-8")
        if old_text == new_text:
            out(f"unchanged: {fwd(path)}")
            return 0
        if not force:
            diff = "".join(difflib.unified_diff(old_text.splitlines(True), new_text.splitlines(True),
                                                fromfile=f"{name}.json (current)", tofile=f"{name}.json (new)"))
            RUN_DIR.mkdir(parents=True, exist_ok=True)
            dfile = RUN_DIR / f"diff-{name}.diff"
            dfile.write_text(diff, encoding="utf-8")
            out(f"EXISTS: profile '{name}' already exists at {fwd(path)}.")
            out(f"diff written to {fwd(dfile)} (UTF-8). Show it to the user; after they approve, rerun with --force.")
            return 3
        out(f"backup: {fwd(backup(path))}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(new_text, encoding="utf-8")
    out(f"{'updated' if force else 'created'}: {fwd(path)}")
    if data.get("agent") is not False:
        write_agents(cwd, only=name)
    return 0


def cmd_rm(name: str, force: bool, cwd: Path) -> int:
    profile = get_profile(cwd, name) if name in load_profiles(cwd) else None
    if not profile:
        raise UserError(f"no profile '{name}'")
    if not force:
        out(f"would delete {fwd(profile['path'])} and its generated agent. Ask the user, then rerun with --force.")
        return 3
    out(f"backup: {fwd(backup(profile['path']))}")
    profile["path"].unlink()
    agent = agent_path(profile)
    if agent.is_file() and AGENT_MARKER in agent.read_text(encoding="utf-8", errors="replace"):
        agent.unlink()
        out(f"removed agent: {fwd(agent)}")
    out(f"deleted: {fwd(profile['path'])}")
    return 0


# ---------------------------------------------------------------- generated subagents


def agent_path(profile: dict) -> Path:
    base = CLAUDE if profile["scope"] == "user" else profile["path"].parents[2]  # <root>/.claude
    return base / "agents" / f"{AGENT_PREFIX}{profile['name']}.md"


def yaml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def agent_text(profile: dict, cwd: Path) -> str:
    data = profile["data"]
    ag = data.get("agent") or {}
    plan = resolve(profile, cwd)
    desc = data.get("description", "").strip() or profile["name"]
    when = data.get("whenToUse", "").strip()
    sep = "" if desc[-1] in ".。!！?？" else "."
    description = f"[SkillPool profile: {profile['name']}] {desc}{sep}" + (f" Use when: {when}" if when else "")
    # only server-level MCP denies are safe here: a Skill(x) entry would remove the whole Skill tool
    deny = [d for d in plan["settings"].get("permissions", {}).get("deny", []) if d.startswith("mcp__")]
    if plan["mcp_config"] is not None:
        keep = {mcp_prefix(n) for n in plan["mcp_config"]["mcpServers"]}
        deny += [p for p in known_mcp_prefixes(cwd) if p not in keep]
    plugins = installed_plugins()
    for pid, on in plan["settings"].get("enabledPlugins", {}).items():
        if not on:
            deny += [mcp_prefix(n) for n in plugin_mcp_servers(plugins[pid]["root"])]
            deny.append(mcp_prefix(plugins[pid]["name"]))  # tools a plugin's mod registers
    deny += ag.get("disallowedTools", [])
    deny = sorted(set(deny))
    fm = ["---", f"name: {AGENT_PREFIX}{profile['name']}", f"description: {yaml_str(description)}"]
    if ag.get("tools"):
        fm.append("tools: " + ", ".join(ag["tools"]))
    if deny:
        fm.append("disallowedTools: " + ", ".join(deny))
    if ag.get("preloadSkills"):
        fm.append("skills: " + ", ".join(ag["preloadSkills"]))
    model = ag.get("model") or data.get("model")
    if model:
        fm.append(f"model: {model}")
    fm.append("---")
    body = [AGENT_MARKER, "",
            f"You are a subagent running under the SkillPool profile `{profile['name']}`.",
            f"Scope: {desc}" + (f" ({when})" if when else ""),
            "Stay within that scope. If the task needs tools or skills outside it, say so in your reply "
            "instead of working around it."]
    if plan["append"]:
        body += ["", plan["append"]]
    return "\n".join(fm) + "\n" + "\n".join(body) + "\n"


def write_agents(cwd: Path, only: str | None = None, dry_run: bool = False) -> int:
    profiles = load_profiles(cwd)
    wanted: dict[Path, str] = {}
    for p in profiles.values():
        if p["errors"] or p["data"].get("agent") is False or (only and p["name"] != only):
            continue
        wanted[agent_path(p)] = agent_text(p, cwd)
    for path, text in wanted.items():
        old = path.read_text(encoding="utf-8") if path.is_file() else None
        if old is not None and AGENT_MARKER not in old:
            err(f"skillpool: {fwd(path)} exists and was not generated by skillpool; left alone")
            continue
        if old == text:
            out(f"agent unchanged: {fwd(path)}")
            continue
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        out(f"agent {'would write' if dry_run else 'written'}: {fwd(path)}")
    if only is None:  # drop generated agents whose profile is gone
        dirs = {CLAUDE / "agents"} | {project_root(cwd) / ".claude" / "agents"}
        for d in dirs:
            for f in d.glob(f"{AGENT_PREFIX}*.md") if d.is_dir() else []:
                if f not in wanted and AGENT_MARKER in f.read_text(encoding="utf-8", errors="replace") \
                        and f.stem[len(AGENT_PREFIX):] not in profiles:
                    if not dry_run:
                        f.unlink()
                    out(f"stale agent {'would remove' if dry_run else 'removed'}: {fwd(f)}")
    return 0


# ---------------------------------------------------------------- shim


def cmd_install_shim(dir_arg: str | None) -> int:
    script = Path(__file__).resolve()
    if dir_arg:
        target = Path(dir_arg)
    else:
        path_dirs = [Path(p) for p in os.environ.get("PATH", "").split(os.pathsep) if p]
        prefs = [HOME / ".local" / "bin", HOME / "bin"]
        target = next((d for d in prefs if any(scan.norm_path(d) == scan.norm_path(p) for p in path_dirs)), None)
        if not target:
            raise UserError("no ~/.local/bin or ~/bin on PATH; pass --dir <a folder on PATH>")
    target.mkdir(parents=True, exist_ok=True)
    py = sys.executable
    written = []
    if os.name == "nt":
        f = target / "skillpool.cmd"
        f.write_text(f'@"{py}" "{script}" %*\r\n', encoding="utf-8")
        written.append(f)
    f = target / "skillpool"
    f.write_text(f'#!/bin/sh\nexec "{fwd(py)}" "{fwd(script)}" "$@"\n', encoding="utf-8", newline="\n")
    try:
        f.chmod(0o755)
    except OSError:
        pass
    written.append(f)
    for f in written:
        out(f"shim written: {fwd(f)}")
    out(f"python: {fwd(py)}")
    return 0


# ---------------------------------------------------------------- main


def take_flag(args: list[str], flag: str) -> bool:
    if flag in args:
        args.remove(flag)
        return True
    return False


def take_value(args: list[str], flag: str) -> str | None:
    if flag in args:
        i = args.index(flag)
        if i + 1 >= len(args):
            raise UserError(f"{flag} needs a value")
        val = args[i + 1]
        del args[i:i + 2]
        return val
    return None


def main(argv: list[str]) -> int:
    cwd = Path.cwd()
    args = list(argv)
    if args and args[0] == "--":  # `skillpool -- <claude args>`: no profile argument
        return launch(os.environ.get("AGENT_PROFILE") or None, args[1:], cwd)
    first = args[0] if args else None
    if first in ("help", "-h", "--help") and len(args) == 1:
        out(__doc__.strip())
        return 0
    if first in SUBCOMMANDS:
        rest = args[1:]
        as_json = take_flag(rest, "--json")
        if first == "list":
            return cmd_list(cwd, as_json)
        if first == "show":
            if not rest:
                raise UserError("usage: skillpool show <profile>")
            return cmd_show(rest[0], cwd, as_json)
        if first == "check":
            return cmd_check(rest[0] if rest else None, cwd, as_json)
        if first == "save":
            force = take_flag(rest, "--force")
            name = take_value(rest, "--name")
            scope = take_value(rest, "--scope") or "user"
            if scope not in ("user", "project") or len(rest) != 1:
                raise UserError("usage: skillpool save <draft.json> [--name N] [--scope user|project] [--force]")
            return cmd_save(Path(rest[0]), name, scope, force, cwd)
        if first == "rm":
            force = take_flag(rest, "--force")
            if len(rest) != 1:
                raise UserError("usage: skillpool rm <profile> [--force]")
            return cmd_rm(rest[0], force, cwd)
        if first == "agents":
            return write_agents(cwd, dry_run=take_flag(rest, "--dry-run"))
        if first == "install-shim":
            return cmd_install_shim(take_value(rest, "--dir"))
    # launch: `skillpool <profile> [claude args]`, or `skillpool [claude args]` with $AGENT_PROFILE
    if first and not first.startswith("-"):
        name, passthrough = first, args[1:]
        if passthrough and passthrough[0] == "--":
            passthrough = passthrough[1:]
    else:
        name, passthrough = os.environ.get("AGENT_PROFILE") or None, args
    return launch(name, passthrough, cwd)


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except UserError as e:
        err(f"skillpool: {e}")
        sys.exit(2)
