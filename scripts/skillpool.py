def resolve(profile: dict, cwd: Path) -> dict:
    """Turn a profile into launch settings / MCP config / appended prompt / extra CLI args."""
    data = profile["data"]
    warnings: list[str] = []  # something in the profile did not resolve
    notes: list[str] = []  # expected limits, and hints
    settings: dict = {}
    plugins = installed_plugins()

    # skills
    sk = data.get("skills", {})
    have_pool = pool_names()
    for n in sk.get("use", []):
        if n not in have_pool and n not in own_skills(profile):
            warnings.append(f"skills.use: '{n}' is not in the pool ({fwd(POOL)}); "
                            f"`skillpool pool add {n}` moves it there")
    overridable, plugin_skills = skill_universe(cwd)
    overrides: dict[str, str] = {}
    for n in sk.get("off", []):
        if n in plugin_skills:
            warnings.append(f"skills.off: '{n}' is a plugin skill; switch its plugin off with plugins.off")
        elif n not in overridable:
            warnings.append(f"skills.off: skill '{n}' not found (run `skillpool check` to refresh built-in names)")
        else:
            overrides[n] = "off"
    if overrides:
        settings["skillOverrides"] = overrides
    for n, src in missing_pool_refs(profile, cwd).items():
        notes.append(f"{src} uses the pool skill '{n}', which this profile does not include; "
                     f"add it to skills.use if this profile needs it")

    # plugins
    enabled: dict[str, bool] = {}
    for key, val in (("off", False), ("on", True)):
        for n in data.get("plugins", {}).get(key, []):
            pid = plugin_id(n, plugins)
            if not pid:
                warnings.append(f"plugins.{key}: no installed plugin '{n}'")
                continue
            if not val and plugins[pid]["name"] == "skillpool":
                notes.append("plugins.off: skillpool stays on, so /skillpool can still switch profiles")
                continue
            enabled[pid] = val
    if enabled:
        settings["enabledPlugins"] = enabled
    off_plugins = {pid for pid, v in enabled.items() if not v}

    # MCP
    mcp = data.get("mcp", {})
    use_project = mcp.get("project", True)
    deny: list[str] = []
    mcp_config = None
    prefixes = known_mcp_prefixes(cwd)
    if "off" in mcp:
        for n in mcp["off"]:
            deny.append(mcp_prefix(n))
            if mcp_prefix(n) not in prefixes:
                warnings.append(f"mcp.off: server '{n}' not seen here")
        notes.append("mcp.off hides tools only: a hidden server still connects and its server "
                     "instructions stay in the prompt. Use mcp.only for full removal")
    if "only" in mcp:
        want = set(mcp["only"])
        servers: dict[str, dict] = {}
        for n, origin, cfg in raw_mcp_sources(cwd, "approved" if use_project else "none"):
            if n in servers or (n not in want and origin != "project"):
                continue  # the project's approved servers come along unless mcp.project is false
            if origin.startswith("plugin:"):
                pid = origin.split(":", 1)[1]
                if pid in off_plugins:
                    continue
                cfg = json.loads(json.dumps(cfg).replace("${CLAUDE_PLUGIN_ROOT}", fwd(plugins[pid]["root"])))
            servers[n] = cfg
        for n in sorted(want - set(servers)):
            if n.startswith("claude.ai"):
                warnings.append(f"mcp.only: claude.ai connector '{n}' cannot be kept under mcp.only")
            elif mcp_prefix(n) not in prefixes:
                warnings.append(f"mcp.only: server '{n}' not configured here")
        mcp_config = {"mcpServers": servers}
        kept = {mcp_prefix(n) for n in servers}
        # tools a mod registers itself are not MCP config, so strict mode leaves them: hide by name
        configured = {mcp_prefix(n) for n, _, _ in raw_mcp_sources(cwd, "all")}
        for p, n in prefixes.items():
            if p not in configured and p not in kept and n not in want and not n.startswith("claude.ai") \
                    and not p.startswith("mcp__claude_ai_"):
                deny.append(p)
        deny += [mcp_prefix(n) for n in BUILTIN_MCP if n not in want]  # built in: strict mode leaves it
    elif not use_project:
        project_names = sorted({n for n, o, _ in raw_mcp_sources(cwd, "all") if o == "project"})
        if project_names:
            settings["disabledMcpjsonServers"] = project_names
    if deny:
        settings["permissions"] = {"deny": sorted(set(deny))}

    # instructions (advanced: the profile's own CLAUDE.md is the main place)
    ins = data.get("instructions", {})
    if ins.get("exclude"):
        settings["claudeMdExcludes"] = exclude_globs(ins["exclude"], cwd)
    prompt = append_text(profile, warnings)

    # memory: the profile's own (session_context); Claude Code's auto memory keys on the folder, so it is off
    mem = memory_dir(profile, cwd)
    settings["autoMemoryEnabled"] = False

    args: list[str] = []
    if data.get("model"):
        args += ["--model", data["model"]]
    if data.get("effort"):
        args += ["--effort", data["effort"]]
    return {"settings": settings, "mcp_config": mcp_config, "append": prompt, "args": args,
            "warnings": warnings, "notes": notes, "memory": mem}


def switch_notes(profile: dict) -> list[str]:
    """What a mid-session switch cannot do for this profile (only a launch can)."""
    data = profile["data"]
    res = []
    if data.get("plugins", {}).get("off"):
        res.append("plugins.off: the plugins stay loaded; their skills, agents and MCP tools are refused")
    if "only" in data.get("mcp", {}) or "off" in data.get("mcp", {}):
        res.append("mcp: the servers stay connected; tools outside the profile are refused")
    if data.get("model") or data.get("effort"):
        res.append("model/effort: not changed (use /model)")
    res.append("memory: Claude Code's own auto memory cannot be switched off mid-session; SkillPool refuses "
               "writes to it while the profile is on")
    if data.get("instructions", {}).get("exclude") or data.get("instructions", {}).get("append"):
        res.append("instructions.exclude/append: apply at launch only")
    if res:
        res.append(f"start with `skillpool {profile['name']}` for all of it")
    return res


