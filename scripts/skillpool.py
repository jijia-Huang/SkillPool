def section_text(text: str, heading: str) -> str | None:
    """The `#`/`##` section titled `heading`, through the next heading of the same or higher level."""
    lines, start, level, in_code = text.splitlines(), None, 0, False
    for i, line in enumerate(lines):
        if line.lstrip().startswith("```"):
            in_code = not in_code
        m = None if in_code else re.match(r"^(#{1,6})\s+(.*?)\s*$", line)
        if not m:
            continue
        if start is None and m.group(2) == heading.strip():
            start, level = i, len(m.group(1))
        elif start is not None and len(m.group(1)) <= level:
            return "\n".join(lines[start:i]).strip()
    return "\n".join(lines[start:]).strip() if start is not None else None


def expand(path: str, base: Path) -> Path:
    p = Path(os.path.expandvars(os.path.expanduser(path)))
    return p if p.is_absolute() else (base / p)


def append_text(profile: dict, warnings: list[str]) -> str:
    """instructions.append: extra files or sections, added to the system prompt at launch."""
    parts = []
    for item in profile["data"].get("instructions", {}).get("append", []):
        file, section = (item, None) if isinstance(item, str) else (item["file"], item.get("section"))
        f = expand(file, profile["dir"])
        if not f.is_file():
            warnings.append(f"instructions.append: {fwd(f)} not found, skipped")
            continue
        text = f.read_text(encoding="utf-8", errors="replace")
        if section:
            body = section_text(text, section)
            if body is None:
                warnings.append(f"instructions.append: section '{section}' not in {fwd(f)}, skipped")
                continue
            text = body
        parts.append(text.strip())
    return "\n\n".join(parts)


def exclude_globs(kinds: list[str], cwd: Path) -> list[str]:
    """claudeMdExcludes patterns. CLAUDE.md shadows AGENTS.md in the same folder, so both go."""
    globs: list[str] = []
    for k in kinds:
        if k == "user":
            globs += [fwd(CLAUDE / n) for n in INSTRUCTION_FILES] + [fwd(CLAUDE / "rules") + "/**"]
        elif k == "project":
            for d in [cwd, *cwd.parents]:
                globs += [fwd(d / n) for n in INSTRUCTION_FILES]
                if scan.norm_path(d) != scan.norm_path(HOME):
                    globs += [fwd(d / ".claude" / "CLAUDE.md"), fwd(d / ".claude" / "rules") + "/**"]
            globs += [fwd(cwd) + "/**/" + n for n in INSTRUCTION_FILES]
        else:
            globs.append(k)
    return list(dict.fromkeys(globs))


def loaded_instruction_files(cwd: Path) -> list[Path]:
    """The global and project instruction files that load here, and the files they @import."""
    files: list[Path] = [CLAUDE / "CLAUDE.md", *sorted((CLAUDE / "rules").glob("*.md"))]
    root = project_root(cwd)
    dirs = []
    for d in [cwd, *cwd.parents]:
        dirs.append(d)
        if scan.norm_path(d) == scan.norm_path(root):
            break
    for d in reversed(dirs):
        files.append(d / "CLAUDE.md" if (d / "CLAUDE.md").is_file() else d / "AGENTS.md")
        files += [d / "CLAUDE.local.md", d / ".claude" / "CLAUDE.md", *sorted((d / ".claude" / "rules").glob("*.md"))]
    files = [f for f in files if f.is_file()]
    for f in list(files):
        for imp in re.findall(r"^\s*@(\S+)", f.read_text(encoding="utf-8", errors="replace"), re.M):
            g = expand(imp, f.parent)
            if g.is_file() and g not in files:
                files.append(g)
    return files


# `/name`, `.claude/skills/name` or `.agents/skills/name`; a word alone, a URL or a path piece is not a reference.
SKILL_REF = re.compile(r"(?:^|[^A-Za-z0-9_./\\:-])/([A-Za-z0-9][A-Za-z0-9_:-]*)(?![A-Za-z0-9_/])"
                       r"|\.(?:claude|agents)[/\\]skills[/\\]([A-Za-z0-9][A-Za-z0-9_-]*)", re.M)


def referenced_skills(text: str, known: set[str]) -> list[str]:
    """Skills the text tells the model to use, by `/name` or by their folder."""
    names = {(a or b).rstrip(":-") for a, b in SKILL_REF.findall(text)}
    return sorted(n for n in names if n in known)


def missing_pool_refs(profile: dict, cwd: Path) -> dict[str, str]:
    """Pool skills that loaded instructions (or the profile's own CLAUDE.md) use but the profile lacks."""
    have = set(profile["data"].get("skills", {}).get("use", [])) | set(own_skills(profile))
    candidates = pool_names() - have
    refs: dict[str, str] = {}
    if not candidates:
        return refs
    md = profile["dir"] / "CLAUDE.md"
    for f in loaded_instruction_files(cwd) + ([md] if md.is_file() else []):
        for n in referenced_skills(f.read_text(encoding="utf-8", errors="replace"), candidates):
            refs.setdefault(n, fwd(f))
    return refs


