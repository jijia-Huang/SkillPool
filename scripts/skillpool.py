def memory_rules(profile: dict, mem: Path) -> str:
    md = fwd(profile["dir"] / "CLAUDE.md")
    return "\n".join([
        "## 記憶規則（SkillPool）",
        f"- 這個 session 的記憶屬於 profile「{profile['name']}」。Claude Code 原生的記憶不用，"
        "不要寫到 `~/.claude/projects/*/memory/`。",
        f"- 跟這個專案有關的記憶寫在 `{fwd(mem)}/`：一個事實一個 `.md` 檔，開頭用 frontmatter（`name`、"
        "`description`、`type`: user／feedback／project／reference），再到同一個資料夾的 `MEMORY.md` 加一行 "
        "`- [標題](檔名.md) — 一句話`。`MEMORY.md` 只放索引，不放內容。",
        f"- 在所有專案都適用的（使用者的偏好、對你做法的回饋）寫進 `{md}` 的「{MEMORY_HEADING[3:]}」一節，"
        "用 Edit，只改那一節。規則區要改請走 `skillpool save`。",
        "- 值得記：使用者是誰與偏好；使用者糾正或肯定你的做法（附原因）；從程式碼和 git 看不出來的決定、限制、時程；"
        "外部資源在哪裡。不要記：程式碼或 git 已經有的、只跟這次對話有關的、密碼與金鑰。",
        "- 寫之前先看有沒有同主題的檔，有就更新，錯的就刪。日期寫絕對日期。使用者叫你記住就記，叫你忘掉就刪。",
        f"- `MEMORY.md` 每行一筆、保持精簡：只有前 {INDEX_LINES} 行會自動載入。",
        "- 記憶可能過時：用到裡面提到的檔案、函式、設定之前，先確認它還在。",
    ])


def memory_index(index: Path) -> str:
    """A MEMORY.md as it goes into the context: its first lines only, and a nudge when it is too long."""
    lines = index.read_text(encoding="utf-8", errors="replace").strip().splitlines()
    kept: list[str] = []
    size = 0
    for line in lines[:INDEX_LINES]:
        size += len(line.encode("utf-8")) + 1
        if size > INDEX_BYTES:
            break
        kept.append(line)
    if len(kept) < len(lines):
        kept.append(f"（MEMORY.md 有 {len(lines)} 行，只載入前 {len(kept)} 行。請精簡這份索引：合併重複的、刪掉過時的，"
                    "細節放進各自的記憶檔。）")
    return "\n".join(kept)


def session_context(profile: dict, cwd: Path, include_rules: bool = True) -> str:
    """What the model gets for this profile here: its CLAUDE.md, this project's memory, the memory rules."""
    mem = memory_dir(profile, cwd)
    parts = [f"# SkillPool profile: {profile['name']}"]
    md = profile["dir"] / "CLAUDE.md"
    if include_rules and md.is_file():
        parts.append(strip_index(md.read_text(encoding="utf-8", errors="replace")).strip())
    index = mem / "MEMORY.md"
    parts.append(f"## 這個專案的記憶（{fwd(mem)}/MEMORY.md）\n" + (memory_index(index) if index.is_file() else "（還沒有）"))
    key = project_key(cwd)
    others = [(k, v) for k, v in (scan.read_json(projects_file(profile)) or {}).items()
              if k != key and (profile["dir"] / "memory" / k / "MEMORY.md").is_file()]
    if others:
        others.sort(key=lambda kv: kv[1].get("lastUsed", ""), reverse=True)
        parts.append("## 這個 profile 在其他專案的記憶（需要參考時再讀）\n" + "\n".join(
            f"- {v.get('path', k)}: `{fwd(profile['dir'] / 'memory' / k / 'MEMORY.md')}`" for k, v in others[:15]))
    parts.append(memory_rules(profile, mem))
    return "\n\n".join(parts)


def cmd_hook(rest: list[str]) -> int:
    """Claude Code's SessionStart hook: the profile's context, at start and after each compaction and /clear."""
    if rest[:1] != ["session-start"]:
        raise UserError("usage: skillpool hook session-start")
    try:
        event = json.loads(sys.stdin.read() or "{}")
    except ValueError:
        event = {}
    name = os.environ.get("AGENT_PROFILE", "")
    profile = load_profiles().get(name) if NAME_RE.match(name) else None
    if not profile or profile["errors"]:
        return 0  # no profile in this session: nothing to add
    cwd = Path(event.get("cwd") or os.getcwd())
    # with the variable on, Claude Code reads the profile's CLAUDE.md from the added folder itself
    text = session_context(profile, cwd, include_rules=os.environ.get(ENV_ADD_DIR_MD) != "1")
    out(json.dumps({"hookSpecificOutput": {"hookEventName": "SessionStart", "additionalContext": text}}))
    return 0


