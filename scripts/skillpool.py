def pool_users() -> dict[str, list[str]]:
    res: dict[str, list[str]] = {}
    for p in load_profiles().values():
        for n in p["data"].get("skills", {}).get("use", []):
            res.setdefault(n, []).append(p["name"])
    return res


def cmd_pool(rest: list[str], as_json: bool) -> int:
    action = rest.pop(0) if rest else "list"
    force = take_flag(rest, "--force")
    users = pool_users()
    if action == "list":
        rows = [{"skill": n, "profiles": users.get(n, [])} for n in sorted(pool_names())]
        if as_json:
            out(json.dumps(rows, ensure_ascii=True, indent=2))
            return 0
        if not rows:
            out(f"the pool is empty ({fwd(POOL)}). `skillpool pool add <skill>` moves a skill from ~/.claude/skills")
        for r in rows:
            out(f"{r['skill']:<32} " + (", ".join(r["profiles"]) or "(no profile uses it)"))
        for n in sorted(set(users) - pool_names()):
            out(f"missing from the pool, used by {', '.join(users[n])}: {n}")
        return 0
    if action not in ("add", "remove"):
        raise UserError(f"unknown pool action '{action}'")
    if len(rest) != 1:
        raise UserError("usage: skillpool pool add <skill> [--force] | pool remove <skill> [--force]")
    n = rest[0]
    src, dst = (CLAUDE / "skills" / n, POOL / n) if action == "add" else (POOL / n, CLAUDE / "skills" / n)
    if is_link(src) or not (src / "SKILL.md").is_file():
        raise UserError(f"no skill folder {fwd(src)}")
    if dst.exists() or is_link(dst):
        raise UserError(f"{fwd(dst)} already exists")
    if action == "add":
        effect = (f"move {fwd(src)} to {fwd(dst)}: sessions without a profile that uses it will no longer "
                  f"see '{n}'; profiles get it with skills.use")
    else:
        effect = (f"move {fwd(src)} back to {fwd(dst)}: every session sees '{n}' again"
                  + (f"; the links in {', '.join(users[n])} are removed (edit their skills.use)"
                     if users.get(n) else ""))
    if not force:
        out(f"would {effect}. Ask the user, then rerun with --force.")
        return 3
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(src), str(dst))
    if action == "remove":
        for p in load_profiles().values():
            link = profile_skill_dir(p) / n
            if is_link(link):
                remove_link(link)
                out(f"unlinked from {p['name']}")
    out(f"moved: {fwd(src)} -> {fwd(dst)}")
    return 0


