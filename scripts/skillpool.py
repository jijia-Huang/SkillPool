"""SkillPool: profiles as folders, layered onto Claude Code sessions.

A profile is a folder, ~/.claude/skillpool/profiles/<name>/:
    CLAUDE.md               the profile's rules and cross-project memory, plus a memory index SkillPool keeps
    profile.json            pool skills (skills.use), plugins, MCP, model, effort, memory
    .claude/skills/<skill>  links into ~/.claude/skillpool/pool/, or the profile's own skills
    memory/<project-key>/   the profile's memory for one project

A session sees its profile two ways. Its skills: through one link, ~/.claude/skillpool/sessions/<id>
-> profiles/<name>, which Claude Code loads as an added directory. Its CLAUDE.md and its memory for the
current project: SkillPool's SessionStart hook (`skillpool hook session-start`) puts them in the context
at start and again after every compaction and /clear. Both stack on top of the user's global setup and the
project's. Claude Code's own auto memory is switched off in profile sessions: the profile's replaces it.
Switching profile = point the link elsewhere, tell the hook (AGENT_PROFILE) and compact.

    skillpool <profile> [claude args...]   start claude with that profile
    skillpool [claude args...]             profile from $AGENT_PROFILE, else plain claude
    skillpool list [--json]                the profiles
    skillpool show <profile> [--json]      what a profile does here, without launching
    skillpool show --draft <file.json> --name N
    skillpool check [<profile>]            start claude headless and read what really loaded
    skillpool new <name> [--description D] [--when W]
    skillpool save <draft.json|draft.md> [--name N] [--force]
    skillpool rm <profile> [--force]
    skillpool pool [list] | pool add <skill> [--force] | pool remove <skill> [--force]
    skillpool agents [--dry-run]           regenerate the skillpool-<profile> subagents
    skillpool session attach --link L --cwd C (<profile> | --empty) [--context] | detach --link L | sweep
    skillpool hook session-start           (Claude Code runs this: prints the profile's context)
    skillpool install-shim [--dir D]

Console output is ASCII only (Chinese text goes to UTF-8 files or \\u escapes).
"""

