def pool_names() -> set[str]:
    return {d.name for d in POOL.iterdir() if d.is_dir() and (d / "SKILL.md").is_file()} if POOL.is_dir() else set()


def profile_skill_dir(profile: dict) -> Path:
    return profile["dir"] / ".claude" / "skills"


def sync_skills(profile: dict) -> list[str]:
    """Make the profile's .claude/skills links match skills.use. Real folders there are the profile's own."""
    changes: list[str] = []
    want = profile["data"].get("skills", {}).get("use", [])
    sk = profile_skill_dir(profile)
    for n in want:
        target = POOL / n
        link = sk / n
        if not (target / "SKILL.md").is_file():
            continue  # reported by resolve()
        if link.exists() and not is_link(link):
            continue  # the profile keeps its own copy
        if not (is_link(link) and same_path(link_target(link), target)):
            make_link(link, target)
            changes.append(f"linked {n}")
    for entry in sorted(sk.iterdir()) if sk.is_dir() else []:
        if is_link(entry) and entry.name not in want:
            remove_link(entry)
            changes.append(f"unlinked {entry.name}")
    return changes


def own_skills(profile: dict) -> list[str]:
    sk = profile_skill_dir(profile)
    return sorted(d.name for d in sk.iterdir() if d.is_dir() and not is_link(d)) if sk.is_dir() else []


