class UserError(Exception):
    pass


def out(text: str = "") -> None:
    print(text.encode("ascii", "backslashreplace").decode("ascii"))


def err(text: str) -> None:
    print(text.encode("ascii", "backslashreplace").decode("ascii"), file=sys.stderr)


def fwd(p: Path | str) -> str:
    return str(p).replace("\\", "/")


def mcp_prefix(server: str) -> str:
    """Tool prefix Claude Code gives a server: `claude.ai Claude Docs` -> `mcp__claude_ai_Claude_Docs`."""
    return "mcp__" + re.sub(r"[^A-Za-z0-9_-]", "_", server)


# ---------------------------------------------------------------- locations


def project_root(cwd: Path) -> Path:
    """Nearest folder with .git or .claude, else cwd. Home is never a project root."""
    for d in [cwd, *cwd.parents]:
        if scan.norm_path(d) == scan.norm_path(HOME):
            break
        if (d / ".git").exists() or (d / ".claude").is_dir():
            return d
    return cwd


def profile_dirs(cwd: Path) -> list[tuple[str, Path]]:
    dirs = [("user", USER_PROFILES)]
    root = project_root(cwd)
    if scan.norm_path(root) != scan.norm_path(HOME):
        dirs.append(("project", root / ".claude" / "skillpool" / "profiles"))
    return dirs


def load_profiles(cwd: Path) -> dict[str, dict]:
    """name -> {name, scope, path, data, errors}. A project profile shadows a user one of the same name."""
    found: dict[str, dict] = {}
    for scope, d in profile_dirs(cwd):
        if not d.is_dir():
            continue
        for f in sorted(d.glob("*.json")):
            try:
                data = json.loads(f.read_text(encoding="utf-8"))
                errors = validate(data)
            except Exception as e:  # broken JSON is listed, not fatal
                data, errors = {}, [f"invalid JSON: {e}"]
            entry = {"name": f.stem, "scope": scope, "path": f, "data": data, "errors": errors}
            if f.stem in found:
                entry["shadows"] = str(found[f.stem]["path"])
            found[f.stem] = entry
    return found


def get_profile(cwd: Path, name: str) -> dict:
    profiles = load_profiles(cwd)
    if name not in profiles:
        known = ", ".join(sorted(profiles)) or "(none)"
        raise UserError(f"no profile '{name}'. Known: {known}. Profiles live in {fwd(USER_PROFILES)} "
                        f"or <project>/.claude/skillpool/profiles")
    p = profiles[name]
    if p["errors"]:
        raise UserError(f"profile '{name}' ({fwd(p['path'])}) is invalid: " + "; ".join(p["errors"]))
    return p


