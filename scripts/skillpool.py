def _str_list(v) -> bool:
    return isinstance(v, list) and all(isinstance(x, str) and x for x in v)


def validate(data) -> list[str]:
    e: list[str] = []
    if not isinstance(data, dict):
        return ["profile must be a JSON object"]
    for k in data:
        if k not in PROFILE_KEYS:
            e.append(f"unknown key '{k}'")
    for k in ("description", "whenToUse", "model", "effort"):
        if k in data and not isinstance(data[k], str):
            e.append(f"'{k}' must be a string")
    if data.get("effort") and data["effort"] not in ("low", "medium", "high", "xhigh", "max"):
        e.append("'effort' must be low/medium/high/xhigh/max")
    sk = data.get("skills", {})
    if not isinstance(sk, dict):
        e.append("'skills' must be an object")
    else:
        for k, v in sk.items():
            if k in ("only", "on", "off", "nameOnly", "userOnly"):
                if not _str_list(v):
                    e.append(f"'skills.{k}' must be a list of skill names")
            elif k == "others":
                if v not in ("off", "name-only", "user-invocable-only"):
                    e.append("'skills.others' must be off / name-only / user-invocable-only")
            else:
                e.append(f"unknown key 'skills.{k}'")
        if "others" in sk and "only" not in sk:
            e.append("'skills.others' needs 'skills.only'")
    pl = data.get("plugins", {})
    if not isinstance(pl, dict) or any(k not in ("off", "on") or not _str_list(v) for k, v in pl.items()):
        e.append("'plugins' must be {\"off\": [...], \"on\": [...]}")
    mcp = data.get("mcp", {})
    if not isinstance(mcp, dict) or any(k not in ("only", "off") or not _str_list(v) for k, v in mcp.items()):
        e.append("'mcp' must be {\"only\": [...]} or {\"off\": [...]}")
    elif "only" in mcp and "off" in mcp:
        e.append("'mcp' takes 'only' or 'off', not both")
    ins = data.get("instructions", {})
    if not isinstance(ins, dict):
        e.append("'instructions' must be an object")
    else:
        for k, v in ins.items():
            if k == "exclude":
                if not _str_list(v):
                    e.append("'instructions.exclude' must be a list (\"user\", \"project\" or globs)")
            elif k == "append":
                if not isinstance(v, list) or not all(
                        (isinstance(x, str) and x) or (isinstance(x, dict) and isinstance(x.get("file"), str)
                                                      and set(x) <= {"file", "section"}) for x in v):
                    e.append("'instructions.append' items are paths or {\"file\", \"section\"}")
            else:
                e.append(f"unknown key 'instructions.{k}'")
    ag = data.get("agent", {})
    if ag is not False:
        if not isinstance(ag, dict):
            e.append("'agent' must be an object or false")
        else:
            for k, v in ag.items():
                if k in ("preloadSkills", "tools", "disallowedTools"):
                    if not _str_list(v):
                        e.append(f"'agent.{k}' must be a list of names")
                elif k == "model":
                    if not isinstance(v, str):
                        e.append("'agent.model' must be a string")
                else:
                    e.append(f"unknown key 'agent.{k}'")
    return e


# ---------------------------------------------------------------- what exists


def read_cache() -> dict:
    return scan.read_json(CACHE_FILE) or {}


def installed_plugins() -> dict[str, dict]:
    """plugin id (name@marketplace) -> {name, root, enabled_user}."""
    user_enabled = (scan.read_json(CLAUDE / "settings.json") or {}).get("enabledPlugins", {}) or {}
    installed = (scan.read_json(CLAUDE / "plugins" / "installed_plugins.json") or {}).get("plugins", {})
    res = {}
    for key, entries in installed.items():
        ents = entries if isinstance(entries, list) else [entries]
        root = next((Path(e["installPath"]) for e in ents if e.get("installPath")), None)
        res[key] = {"name": key.split("@")[0], "root": root, "enabled_user": user_enabled.get(key)}
    return res


def plugin_id(name: str, plugins: dict[str, dict]) -> str | None:
    if name in plugins:
        return name
    hits = [k for k, v in plugins.items() if v["name"] == name]
    return hits[0] if len(hits) == 1 else None


def plugin_mcp_servers(root: Path | None) -> dict[str, dict]:
    if not root:
        return {}
    pm = scan.read_json(root / ".mcp.json") or {}
    servers = pm.get("mcpServers") if isinstance(pm.get("mcpServers"), dict) else pm
    return {n: c for n, c in servers.items() if isinstance(c, dict)}


def raw_mcp_sources(cwd: Path) -> list[tuple[str, str, dict]]:
    """(name, origin, raw config) for every server Claude Code would load here, plugins included.
    Raw configs can hold secrets: they are only ever written to the per-launch run file."""
    res: list[tuple[str, str, dict]] = []
    cj = scan.read_json(HOME / ".claude.json") or {}
    for n, c in (cj.get("mcpServers") or {}).items():
        res.append((n, "user", c))
    here = {scan.norm_path(d) for d in [cwd, *cwd.parents]}
    for p, v in (cj.get("projects") or {}).items():
        if scan.norm_path(p) in here:
            for n, c in (v.get("mcpServers") or {}).items():
                res.append((n, f"local:{p}", c))
    root = project_root(cwd)
    for n, c in ((scan.read_json(root / ".mcp.json") or {}).get("mcpServers") or {}).items():
        res.append((n, "project", c))
    for key, info in installed_plugins().items():
        if info["enabled_user"] is False:
            continue
        for n, c in plugin_mcp_servers(info["root"]).items():
            res.append((n, f"plugin:{key}", c))
    return res


def skill_universe(cwd: Path) -> tuple[set[str], set[str]]:
    """(names skillOverrides can switch, plugin skill names it cannot)."""
    root = scan.norm_path(project_root(cwd))
    inv = scan.inventory([str(project_root(cwd))])
    overridable = {s["name"] for s in inv["skills"] if s["source"] != "plugin"}
    # a local/project-scope plugin only loads in the projects it was installed for
    plugin_skills = {s["name"] for s in inv["skills"] if s["source"] == "plugin"
                     and (s.get("scope") == "user" or root in {scan.norm_path(p) for p in s.get("projects") or []})}
    overridable |= scan.BUNDLED_SKILLS
    plugin_names = {v["name"] for v in installed_plugins().values()}
    for n in read_cache().get("skills", []):
        if ":" in n and n.split(":")[0] in plugin_names:
            plugin_skills.add(n)
        else:
            overridable.add(n)  # bundled and claude.ai skills (anthropic-skills:*) seen by `check`
    return overridable, plugin_skills


def current_overrides(cwd: Path) -> dict[str, str]:
    """skillOverrides already in effect here (user settings, then the project's own files)."""
    res: dict[str, str] = {}
    root = project_root(cwd)
    for f in (CLAUDE / "settings.json", root / ".claude" / "settings.json", root / ".claude" / "settings.local.json"):
        res.update((scan.read_json(f) or {}).get("skillOverrides") or {})
    return res


def known_mcp_prefixes(cwd: Path) -> dict[str, str]:
    """tool prefix -> server name, from configs plus what `check` saw (claude.ai connectors, mod tools)."""
    res = {mcp_prefix(n): n for n, _, _ in raw_mcp_sources(cwd)}
    for n in read_cache().get("mcp", []):
        res.setdefault(mcp_prefix(n), n)
    for p in read_cache().get("mcp_prefixes", []):
        res.setdefault(p, p[len("mcp__"):])
    return res


