def cmd_install_shim(dir_arg: str | None) -> int:
    script = Path(__file__).resolve()
    if dir_arg:
        target = Path(dir_arg)
    else:
        path_dirs = [Path(p) for p in os.environ.get("PATH", "").split(os.pathsep) if p]
        prefs = [HOME / ".local" / "bin", HOME / "bin"]
        target = next((d for d in prefs if any(scan.norm_path(d) == scan.norm_path(p) for p in path_dirs)), None)
        if not target:
            raise UserError("no ~/.local/bin or ~/bin on PATH; pass --dir <a folder on PATH>")
    target.mkdir(parents=True, exist_ok=True)
    py = sys.executable
    written = []
    if os.name == "nt":
        f = target / "skillpool.cmd"
        f.write_text(f'@"{py}" "{script}" %*\r\n', encoding="utf-8")
        written.append(f)
    f = target / "skillpool"
    f.write_text(f'#!/bin/sh\nexec "{fwd(py)}" "{fwd(script)}" "$@"\n', encoding="utf-8", newline="\n")
    try:
        f.chmod(0o755)
    except OSError:
        pass
    written.append(f)
    SP_HOME.mkdir(parents=True, exist_ok=True)
    CONFIG_FILE.write_text(json.dumps({"python": py, "script": str(script)}, indent=2), encoding="utf-8")
    written.append(CONFIG_FILE)
    for f in written:
        out(f"written: {fwd(f)}")
    out(f"python: {fwd(py)}")
    return 0


