# ---------------------------------------------------------------- links
# A link is a junction on Windows (no admin rights needed), a symlink elsewhere. Removing one
# never touches what it points at; nothing here deletes a folder that could hold a link.


def is_link(p: Path) -> bool:
    try:
        return p.is_symlink() or os.path.isjunction(p)
    except OSError:
        return False


def link_target(p: Path) -> Path | None:
    try:
        t = os.readlink(p)
    except OSError:
        return None
    return Path(t[4:] if t.startswith("\\\\?\\") else t)


def same_path(a: Path | None, b: Path) -> bool:
    return a is not None and scan.norm_path(a) == scan.norm_path(b)


def make_link(link: Path, target: Path) -> None:
    """Point `link` at `target`, replacing a link that is there. Never replaces a real folder or file."""
    if is_link(link):
        if same_path(link_target(link), target):
            return
        remove_link(link)
    elif link.exists():
        raise UserError(f"{fwd(link)} exists and is not a link; left alone")
    link.parent.mkdir(parents=True, exist_ok=True)
    if os.name == "nt":
        import _winapi
        _winapi.CreateJunction(str(target), str(link))
    else:
        os.symlink(target, link, target_is_directory=True)


def remove_link(link: Path) -> None:
    """Remove the link itself; refuses anything that is not a link."""
    if not is_link(link):
        raise UserError(f"refusing to remove {fwd(link)}: not a link")
    if os.name == "nt" and os.path.isjunction(link):
        os.rmdir(link)  # removes the junction, not the folder it points at
    else:
        os.unlink(link)


# ---------------------------------------------------------------- locations


def project_root(cwd: Path) -> Path:
    """Nearest folder with .git or .claude, else cwd. Home is never a project root."""
    for d in [cwd, *cwd.parents]:
        if scan.norm_path(d) == scan.norm_path(HOME):
            break
        if (d / ".git").exists() or (d / ".claude").is_dir():
            return d
    return cwd


def project_key(cwd: Path) -> str:
    """The project's folder name in Claude Code's style: D:\\Tool\\App -> D--Tool-App."""
    return re.sub(r"[^A-Za-z0-9]", "-", str(project_root(cwd)))


# ---------------------------------------------------------------- profiles


def load_profiles() -> dict[str, dict]:
    """name -> {name, dir, path, data, errors}."""
    found: dict[str, dict] = {}
    if not PROFILES.is_dir():
        return found
    for d in sorted(PROFILES.iterdir()):
        if not d.is_dir() or is_link(d):
            continue
        f = d / "profile.json"
        entry = {"name": d.name, "dir": d, "path": f, "data": {}, "errors": []}
        if not NAME_RE.match(d.name) or d.name in SUBCOMMANDS:
            entry["errors"] = [f"bad folder name '{d.name}': lowercase letters, digits and '-'"]
        elif not f.is_file():
            entry["errors"] = ["no profile.json"]
        else:
            try:
                entry["data"] = json.loads(f.read_text(encoding="utf-8"))
                entry["errors"] = validate(entry["data"])
            except Exception as e:  # broken JSON is listed, not fatal
                entry["errors"] = [f"invalid JSON: {e}"]
        found[d.name] = entry
    return found


def legacy_files() -> list[Path]:
    """v0.3 profiles (profiles/<name>.json): no longer read."""
    return sorted(PROFILES.glob("*.json")) if PROFILES.is_dir() else []


def get_profile(name: str) -> dict:
    profiles = load_profiles()
    if name not in profiles:
        known = ", ".join(sorted(profiles)) or "(none)"
        raise UserError(f"no profile '{name}'. Known: {known}. Create one with `skillpool new {name}`")
    p = profiles[name]
    if p["errors"]:
        raise UserError(f"profile '{name}' ({fwd(p['dir'])}) is invalid: " + "; ".join(p["errors"]))
    return p


def _str_list(v) -> bool:
    return isinstance(v, list) and all(isinstance(x, str) and x for x in v)


def validate(data) -> list[str]:
    e: list[str] = []
    if not isinstance(data, dict):
        return ["profile.json must be a JSON object"]
    for k in data:
        if k not in PROFILE_KEYS:
            e.append(f"unknown key '{k}'")
    for k in ("description", "whenToUse", "model", "effort"):
        if k in data and not isinstance(data[k], str):
            e.append(f"'{k}' must be a string")
    if data.get("effort") and data["effort"] not in ("low", "medium", "high", "xhigh", "max"):
        e.append("'effort' must be low/medium/high/xhigh/max")
    sk = data.get("skills", {})
    if not isinstance(sk, dict) or any(k not in ("use", "off") or not _str_list(v) for k, v in sk.items()):
        e.append("'skills' must be {\"use\": [...], \"off\": [...]}")
    pl = data.get("plugins", {})
    if not isinstance(pl, dict) or any(k not in ("off", "on") or not _str_list(v) for k, v in pl.items()):
        e.append("'plugins' must be {\"off\": [...], \"on\": [...]}")
    mcp = data.get("mcp", {})
    if not isinstance(mcp, dict):
        e.append("'mcp' must be an object")
    else:
        for k, v in mcp.items():
            if k in ("only", "off"):
                if not _str_list(v):
                    e.append(f"'mcp.{k}' must be a list of server names")
            elif k == "project":
                if not isinstance(v, bool):
                    e.append("'mcp.project' must be true or false")
            else:
                e.append(f"unknown key 'mcp.{k}'")
        if "only" in mcp and "off" in mcp:
            e.append("'mcp' takes 'only' or 'off', not both")
    ins = data.get("instructions", {})
    if not isinstance(ins, dict):
        e.append("'instructions' must be an object")
    else:
        for k, v in ins.items():
            if k == "exclude":
                if not _str_list(v):
                    e.append("'instructions.exclude' must be a list (\"user\", \"project\" or globs)")
            elif k == "append":
                if not isinstance(v, list) or not all(
                        (isinstance(x, str) and x) or (isinstance(x, dict) and isinstance(x.get("file"), str)
                                                      and set(x) <= {"file", "section"}) for x in v):
                    e.append("'instructions.append' items are paths or {\"file\", \"section\"}")
            else:
                e.append(f"unknown key 'instructions.{k}'")
    ag = data.get("agent", {})
    if ag is not False:
        if not isinstance(ag, dict):
            e.append("'agent' must be an object or false")
        else:
            for k, v in ag.items():
                if k in ("preloadSkills", "tools", "disallowedTools"):
                    if not _str_list(v):
                        e.append(f"'agent.{k}' must be a list of names")
                elif k == "model":
                    if not isinstance(v, str):
                        e.append("'agent.model' must be a string")
                elif k == "omitClaudeMd":
                    if not isinstance(v, bool):
                        e.append("'agent.omitClaudeMd' must be true or false")
                else:
                    e.append(f"unknown key 'agent.{k}'")
    return e


# ---------------------------------------------------------------- CLAUDE.md and memory


def claude_md_template(name: str, description: str = "") -> str:
    return (f"# {name} profile\n\n{description or '(這個 profile 的用途)'}\n\n"
            "## 規則\n\n(這個 profile 的做事方式與注意事項。修改請走 `skillpool save`，會先給使用者看 diff。)\n\n"
            f"{MEMORY_HEADING}\n\n(在所有專案都適用的經驗。模型可以直接更新這一節。)\n\n"
            f"{INDEX_START}\n{INDEX_END}\n")


def strip_index(text: str) -> str:
    """CLAUDE.md without the managed index block (what a person edits and a diff should show)."""
    return re.sub(re.escape(INDEX_START) + r".*?" + re.escape(INDEX_END) + r"\n?", "", text, flags=re.S)


def projects_file(profile: dict) -> Path:
    return profile["dir"] / "memory" / "projects.json"


def note_project(profile: dict, cwd: Path) -> None:
    """Record that this profile was used in this project (the index lists it)."""
    f = projects_file(profile)
    data = scan.read_json(f) or {}
    data[project_key(cwd)] = {"path": str(project_root(cwd)), "lastUsed": today()}
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")


def index_block(profile: dict) -> str:
    d = profile["dir"]
    projects = scan.read_json(projects_file(profile)) or {}
    rows = sorted(projects.items(), key=lambda kv: kv[1].get("lastUsed", ""), reverse=True)[:30]
    lines = [INDEX_START,
             "## 記憶索引（SkillPool 自動維護，請勿手動修改）",
             f"- 這個 profile 的資料夾：`{fwd(d)}`",
             "- 每個專案的記憶在 `memory/<project-key>/`，入口是那裡的 `MEMORY.md`。"
             "project-key = 專案根目錄路徑把英數字以外的字元換成 `-`（`D:\\Tool\\App` → `D--Tool-App`）。",
             "- SkillPool 會在 session 開始、壓縮後和 `/clear` 後，把目前專案的 `MEMORY.md` 和記憶規則放進對話。",
             f"- 在所有專案都適用的經驗，寫在上面的「{MEMORY_HEADING[3:]}」。"]
    if rows:
        lines += ["", "| project-key | 專案 | 最後使用 | 記憶 |", "|---|---|---|---|"]
        for key, info in rows:
            mem = d / "memory" / key / "MEMORY.md"
            lines.append(f"| {key} | {info.get('path', '')} | {info.get('lastUsed', '')} | "
                         + (f"memory/{key}/MEMORY.md" if mem.is_file() else "(尚無)") + " |")
    lines.append(INDEX_END)
    return "\n".join(lines)


def update_index(profile: dict) -> None:
    md = profile["dir"] / "CLAUDE.md"
    text = md.read_text(encoding="utf-8") if md.is_file() else claude_md_template(profile["name"])
    block = index_block(profile)
    if INDEX_START in text and INDEX_END in text:
        new = re.sub(re.escape(INDEX_START) + r".*?" + re.escape(INDEX_END), lambda _: block, text, flags=re.S)
    else:
        new = text.rstrip() + "\n\n" + block + "\n"
    if new != text:
        md.write_text(new, encoding="utf-8")


