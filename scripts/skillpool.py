def take_flag(args: list[str], flag: str) -> bool:
    if flag in args:
        args.remove(flag)
        return True
    return False


def take_value(args: list[str], flag: str) -> str | None:
    if flag in args:
        i = args.index(flag)
        if i + 1 >= len(args):
            raise UserError(f"{flag} needs a value")
        val = args[i + 1]
        del args[i:i + 2]
        return val
    return None


def main(argv: list[str]) -> int:
    cwd = Path.cwd()
    args = list(argv)
    if args and args[0] == "--":  # `skillpool -- <claude args>`: no profile argument
        return launch(os.environ.get("AGENT_PROFILE") or None, args[1:], cwd)
    first = args[0] if args else None
    if first in ("help", "-h", "--help") and len(args) == 1:
        out(__doc__.strip())
        return 0
    if first in SUBCOMMANDS:
        rest = args[1:]
        as_json = take_flag(rest, "--json")
        if first == "list":
            return cmd_list(as_json)
        if first == "show":
            draft = take_value(rest, "--draft")
            if draft:
                return cmd_show("", cwd, as_json, draft_profile(Path(draft), take_value(rest, "--name")))
            if not rest:
                raise UserError("usage: skillpool show <profile> | show --draft <file.json> [--name N]")
            return cmd_show(rest[0], cwd, as_json)
        if first == "check":
            return cmd_check(rest[0] if rest else None, cwd, as_json)
        if first == "new":
            desc, when = take_value(rest, "--description"), take_value(rest, "--when")
            if len(rest) != 1:
                raise UserError("usage: skillpool new <name> [--description D] [--when W]")
            return cmd_new(rest[0], desc, when)
        if first == "save":
            force = take_flag(rest, "--force")
            name = take_value(rest, "--name")
            if len(rest) != 1:
                raise UserError("usage: skillpool save <draft.json|draft.md> [--name N] [--force]")
            return cmd_save(Path(rest[0]), name, force)
        if first == "rm":
            force = take_flag(rest, "--force")
            if len(rest) != 1:
                raise UserError("usage: skillpool rm <profile> [--force]")
            return cmd_rm(rest[0], force)
        if first == "pool":
            return cmd_pool(rest, as_json)
        if first == "agents":
            return write_agents(dry_run=take_flag(rest, "--dry-run"))
        if first == "session":
            return cmd_session(rest)
        if first == "hook":
            return cmd_hook(rest)
        if first == "install-shim":
            return cmd_install_shim(take_value(rest, "--dir"))
    # launch: `skillpool <profile> [claude args]`, or `skillpool [claude args]` with $AGENT_PROFILE
    if first and not first.startswith("-"):
        name, passthrough = first, args[1:]
        if passthrough and passthrough[0] == "--":
            passthrough = passthrough[1:]
    else:
        name, passthrough = os.environ.get("AGENT_PROFILE") or None, args
    return launch(name, passthrough, cwd)


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except UserError as e:
        err(f"skillpool: {e}")
        sys.exit(2)
